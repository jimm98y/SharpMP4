		/// <summary>
		/// The containers of a box, of its class and type, or of a class it derives from and its type: null where its
		/// definitions give none of them.
		/// </summary>
		public static string[] Of(Box box)
		{
			string type = IsoStream.ToFourCC(box.FourCC);
			for (var cls = box.GetType(); cls != null && cls != typeof(Box); cls = cls.BaseType)
				if (containers.TryGetValue(cls.Name + "|" + type, out var places))
					return places;
			return null;
		}

		/// <summary>The containers of a type, of every definition of it, whatever its class: null of one none places.</summary>
		public static string[] OfType(uint fourCC) => containers.TryGetValue(IsoStream.ToFourCC(fourCC), out var places) ? places : null;
	}

